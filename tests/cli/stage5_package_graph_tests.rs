/// A repository that holds a symbolic link is not checked out into the
/// cache. FAILS on the base: the clone was cached and the link followed.
#[cfg(unix)]
#[test]
fn a_symlink_in_a_git_dependency_is_rejected() {
    let ws = fresh_workspace("symlink_git");
    if !git_installed() {
        return;
    }
    let repo = ws.join("lib");
    fs::create_dir_all(repo.join("src")).unwrap();
    fs::write(
        repo.join("silt.toml"),
        "[package]\nname = \"remote\"\nversion = \"0.1.0\"\n",
    )
    .unwrap();
    std::os::unix::fs::symlink("/etc/hostname", repo.join("src/lib.silt")).unwrap();
    commit_all(&ws, &repo, "a link");

    let app = ws.join("app");
    write_package(
        &app,
        "app",
        &["remote = { git = \"../lib\", branch = \"main\" }"],
        "main.silt",
        "import remote\nfn main() {}\n",
    );

    let out = silt(&ws, &app, &["check"]);

    let err = stderr(&out);
    assert_eq!(out.status.code(), Some(1), "{err}");
    assert!(
        err.starts_with(
            "error[package]: dependency `remote` contains a symbolic link: `src/lib.silt`"
        ) && err.contains(" --> silt.toml:6:10"),
        "{err}"
    );
    // Nothing was left in the cache for it.
    let cached: Vec<PathBuf> = fs::read_dir(ws.join("cache/silt/git"))
        .map(|dirs| {
            dirs.flatten()
                .flat_map(|d| fs::read_dir(d.path()).into_iter().flatten().flatten())
                .map(|e| e.path())
                .collect()
        })
        .unwrap_or_default();
    assert!(
        cached.is_empty(),
        "the checkout must not be cached: {cached:?}"
    );
    let _ = fs::remove_dir_all(&ws);
}

// ── Identity by source ────────────────────────────────────────────────

/// Two keys naming one directory give one package, known by both keys.
#[test]
fn two_keys_for_one_source_are_one_package() {
    let ws = fresh_workspace("two_keys");
    let app = ws.join("app");
    write_package(
        &app,
        "app",
        &[
            "a = { path = \"../shared\" }",
            "b = { path = \"../x/../shared\" }",
        ],
        "main.silt",
        "fn main() {}\n",
    );
    write_package(
        &ws.join("shared"),
        "shared",
        &[],
        "lib.silt",
        "pub fn f() { 1 }\n",
    );

    let graph = resolve_packages(&app, LockPolicy::ReadOnly, &mut SourceMap::new())
        .unwrap_or_else(|d| panic!("{d:?}"));

    assert_eq!(graph.packages.len(), 2, "{graph:?}");
    let a = graph.dependency(graph.root, intern::intern("a"));
    let b = graph.dependency(graph.root, intern::intern("b"));
    assert!(a.is_some() && a == b, "{graph:?}");
    let shared = graph.package(a.unwrap());
    assert_eq!(intern::resolve(shared.name), "shared");
    assert!(
        shared.src.ends_with(Path::new("shared").join("src")),
        "{shared:?}"
    );
    let _ = fs::remove_dir_all(&ws);
}

