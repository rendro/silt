// ── Relative git URLs ─────────────────────────────────────────────────

/// A repository `lib` beside the app, holding the package `remote`.
fn sibling_repository(ws: &Path, body: &str) -> String {
    let repo = ws.join("lib");
    write_package(&repo, "remote", &[], "lib.silt", body);
    commit_all(ws, &repo, "one")
}

/// `git = "../lib"` is relative to silt.toml, wherever silt runs. FAILS
/// on the base: git resolved it against the working directory,
/// `app/src`, where there is no `../lib`.
#[test]
fn a_relative_git_url_resolves_against_the_manifest_from_another_directory() {
    let ws = fresh_workspace("rel_git_cwd");
    if !git_installed() {
        return;
    }
    let head = sibling_repository(&ws, "pub fn v() { \"from lib\" }\n");
    let app = ws.join("app");
    write_package(
        &app,
        "app",
        &["remote = { git = \"../lib\", branch = \"main\" }"],
        "main.silt",
        "import remote\nfn main() { println(remote.v()) }\n",
    );

    let out = silt(&ws, &app.join("src"), &["run"]);

    assert!(out.status.success(), "{}", stderr(&out));
    assert_eq!(stdout(&out), "from lib\n");
    let lock = fs::read_to_string(app.join("silt.lock")).unwrap();
    assert!(
        lock.contains(&format!("git = {}", toml_path(&ws.join("lib"))))
            && lock.contains(&format!("rev = \"{head}\"")),
        "the lock records the URL made absolute and the commit:\n{lock}"
    );
    let _ = fs::remove_dir_all(&ws);
}

