// ── A rev that is a commit prefix ─────────────────────────────────────

/// A repository with two commits and a tag named like the first commit's
/// 7-character prefix, pointing at the second. The manifest's `rev` is
/// that prefix: it names the first commit, never the tag. FAILS on the
/// base: `git checkout <prefix>` took the tag, and the lock pinned the
/// prefix.
#[test]
fn a_short_rev_is_the_commit_it_starts_never_a_tag_of_that_name() {
    let ws = fresh_workspace("short_rev");
    if !git_installed() {
        return;
    }
    let repo = ws.join("lib");
    write_package(&repo, "remote", &[], "lib.silt", "pub fn v() { \"one\" }\n");
    let first = commit_all(&ws, &repo, "one");
    fs::write(repo.join("src/lib.silt"), "pub fn v() { \"two\" }\n").unwrap();
    let second = commit_all(&ws, &repo, "two");
    let prefix = &first[..7];
    git(&ws, &repo, &["tag", prefix, &second]);

    let app = ws.join("app");
    let dep = format!("remote = {{ git = \"../lib\", rev = \"{prefix}\" }}");
    write_package(
        &app,
        "app",
        &[&dep],
        "main.silt",
        "import remote\nfn main() { println(remote.v()) }\n",
    );

    let out = silt(&ws, &app, &["run"]);

    assert!(out.status.success(), "{}", stderr(&out));
    assert_eq!(stdout(&out), "one\n", "the prefix names the first commit");
    let lock = fs::read_to_string(app.join("silt.lock")).unwrap();
    assert!(
        lock.contains(&format!("rev = \"{first}\"")),
        "the lock stores the full commit id:\n{lock}"
    );
    // The second run reuses the pin.
    let again = silt(&ws, &app, &["run"]);
    assert_eq!(stdout(&again), "one\n", "{}", stderr(&again));
    assert!(!stderr(&again).contains("Updating"), "{}", stderr(&again));
    let _ = fs::remove_dir_all(&ws);
}

