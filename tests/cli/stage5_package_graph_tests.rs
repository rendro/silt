//! The package graph (`package_graph::resolve_packages`) through the
//! binary: what a lockfile may and may not decide, relative git URLs, a
//! git `rev` that is a commit prefix, and symbolic links in a
//! dependency. The golden cases under `tests/golden/cli/packages/stage5_pkg__*`
//! cover what needs no lockfile and no repository.
//!
//! Hermeticity: every `silt` invocation gets a git checkout cache inside
//! its own workspace (`XDG_CACHE_HOME`, `LOCALAPPDATA`) and an empty git
//! configuration. Nothing uses the network: the repositories are local
//! directories built by the test. Tests that build one are skipped when
//! `git` is not installed.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::sync::atomic::{AtomicUsize, Ordering};

use silt::intern;
use silt::package_graph::{LockPolicy, resolve_packages};
use silt::source::SourceMap;

static COUNTER: AtomicUsize = AtomicUsize::new(0);

fn fresh_workspace(tag: &str) -> PathBuf {
    let n = COUNTER.fetch_add(1, Ordering::SeqCst);
    let dir =
        std::env::temp_dir().join(format!("silt_stage5_pkg_{tag}_{}_{n}", std::process::id()));
    let _ = fs::remove_dir_all(&dir);
    fs::create_dir_all(&dir).unwrap();
    fs::write(dir.join("gitconfig"), "").unwrap();
    dir
}

fn isolate_git(cmd: &mut Command, ws: &Path) {
    cmd.env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_CONFIG_GLOBAL", ws.join("gitconfig"))
        .env("GIT_TERMINAL_PROMPT", "0");
    for var in ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"] {
        cmd.env_remove(var);
    }
}

/// Run `silt <args>` in `cwd` with the checkout cache in `ws`.
fn silt(ws: &Path, cwd: &Path, args: &[&str]) -> Output {
    let mut cmd = Command::new(env!("CARGO_BIN_EXE_silt"));
    cmd.args(args)
        .current_dir(cwd)
        .env("XDG_CACHE_HOME", ws.join("cache"))
        .env("LOCALAPPDATA", ws.join("cache"))
        .env("NO_COLOR", "1");
    isolate_git(&mut cmd, ws);
    cmd.output().expect("failed to spawn silt binary")
}

fn stdout(out: &Output) -> String {
    String::from_utf8_lossy(&out.stdout).into_owned()
}

fn stderr(out: &Output) -> String {
    String::from_utf8_lossy(&out.stderr).into_owned()
}

/// A package at `dir`: `silt.toml` with `name` and the `[dependencies]`
/// lines `deps`, and `src/<file>` holding `body`.
fn write_package(dir: &Path, name: &str, deps: &[&str], file: &str, body: &str) {
    fs::create_dir_all(dir.join("src")).unwrap();
    let mut manifest = format!("[package]\nname = \"{name}\"\nversion = \"0.1.0\"\n");
    if !deps.is_empty() {
        manifest.push_str("\n[dependencies]\n");
        for dep in deps {
            manifest.push_str(dep);
            manifest.push('\n');
        }
    }
    fs::write(dir.join("silt.toml"), manifest).unwrap();
    fs::write(dir.join("src").join(file), body).unwrap();
}

fn git_installed() -> bool {
    let ok = Command::new("git")
        .arg("--version")
        .output()
        .map(|out| out.status.success())
        .unwrap_or(false);
    if !ok {
        eprintln!("SKIP: `git` is not installed");
    }
    ok
}

/// Run `git <args>` in `cwd` with a fixed identity; trimmed stdout.
fn git(ws: &Path, cwd: &Path, args: &[&str]) -> String {
    let mut cmd = Command::new("git");
    cmd.args(["-c", "user.name=silt tests"])
        .args(["-c", "user.email=tests@silt.local"])
        .args(["-c", "commit.gpgsign=false"])
        .args(args)
        .current_dir(cwd);
    isolate_git(&mut cmd, ws);
    let out = cmd.output().expect("spawn git");
    assert!(
        out.status.success(),
        "git {args:?} failed: {}",
        String::from_utf8_lossy(&out.stderr)
    );
    String::from_utf8_lossy(&out.stdout).trim().to_string()
}

/// Make `repo` a repository on the branch `main` and commit everything
/// in it; returns the commit id.
fn commit_all(ws: &Path, repo: &Path, message: &str) -> String {
    if !repo.join(".git").exists() {
        git(ws, repo, &["init", "--quiet"]);
        git(ws, repo, &["symbolic-ref", "HEAD", "refs/heads/main"]);
    }
    git(ws, repo, &["add", "-A"]);
    git(ws, repo, &["commit", "--quiet", "-m", message]);
    git(ws, repo, &["rev-parse", "HEAD"])
}

/// The canonical form of `path` as silt writes it into silt.lock: a
/// TOML string, without the `\\?\` prefix Windows gives a canonical
/// path.
fn toml_path(path: &Path) -> String {
    let canonical = fs::canonicalize(path).unwrap().display().to_string();
    let plain = canonical.strip_prefix(r"\\?\").unwrap_or(&canonical);
    format!("\"{}\"", plain.replace('\\', "\\\\"))
}

const LOCK_HEADER: &str = "# This file is generated by silt. Do not edit by hand.\nversion = 1\n";

/// An app whose manifest gives `x = { path = "good" }`, with packages
/// named `x` at `good/` and `evil/`, and a lockfile that pins `x` to
/// `evil`.
fn app_with_a_lock_pinning_another_source(ws: &Path) -> PathBuf {
    let app = ws.join("app");
    write_package(
        &app,
        "app",
        &["x = { path = \"good\" }"],
        "main.silt",
        "import x\nfn main() { println(x.which()) }\n",
    );
    for which in ["good", "evil"] {
        write_package(
            &app.join(which),
            "x",
            &[],
            "lib.silt",
            &format!("pub fn which() {{ \"{which}\" }}\n"),
        );
    }
    fs::write(
        app.join("silt.lock"),
        format!(
            "{LOCK_HEADER}\n[[package]]\nname = \"app\"\nversion = \"0.1.0\"\n\n\
             [[package]]\nname = \"x\"\nversion = \"0.1.0\"\n\
             source = {{ path = {} }}\nchecksum = \"sha256:0\"\n",
            toml_path(&app.join("evil"))
        ),
    )
    .unwrap();
    app
}

// ── The lockfile never overrides the manifest ─────────────────────────

/// FAILS on the base: only the names in the lock were compared with the
/// manifest, so the lock's `evil` was loaded.
#[test]
fn a_lock_entry_for_another_source_is_stale_and_rewritten() {
    let ws = fresh_workspace("lock_override");
    let app = app_with_a_lock_pinning_another_source(&ws);

    let out = silt(&ws, &app, &["run"]);

    assert!(out.status.success(), "{}", stderr(&out));
    assert_eq!(stdout(&out), "good\n", "stderr: {}", stderr(&out));
    assert!(
        stderr(&out).contains("Updating silt.lock"),
        "{}",
        stderr(&out)
    );
    let lock = fs::read_to_string(app.join("silt.lock")).unwrap();
    assert!(
        lock.contains(&format!("path = {}", toml_path(&app.join("good")))),
        "the rewritten lock pins the manifest's source:\n{lock}"
    );
    let _ = fs::remove_dir_all(&ws);
}

